// Package tray 系统托盘：让没有窗口的常驻进程「看得见、点得到、停得掉」。
//
// 行为语义的唯一真源是 docs/TRAY-CONTRACT.md。
// 用法见 docs/USAGE.md。
//
// # 能力版图
//
// 原生菜单内核：图标 / tooltip / 菜单（含子菜单）/ 左键 / 气泡通知 / 单实例 /
// DPI 图标选档 / Explorer 重启恢复 / Shell 调用退避重试。
//
// 自绘玻璃菜单引擎：半透明底板 + 圆角 + 状态色点 + 明暗跟随，**不支持子菜单**
// （整份降级原生）。三十轮截图验收打磨的实现，本仓只维护不重写。
//
// # 为什么先定契约
//
// 托盘的能力细节（Explorer 重启恢复、DPI 选档、V4 回调、深色跟随）极易漏做，
// 且漏了往往没有现象——键盘用户打不开菜单、Explorer 重启后图标消失，要靠真实
// 场景才暴露。这份契约把踩过的坑固化成编号规则（C-1 ~ C-17），任何语言的实现
// 都可以对照自查。
//
// # 硬约束
//
//   - 内核不认业务：端口号、服务名、任务名、URL 都不许进内核；图标由调用方传 []byte
//   - 非 Windows 走桩（ErrUnsupported），build tag 隔离，交叉构建不碰 user32 符号
//   - 不引第三方托盘库：会破坏「单二进制 + 交叉编译」口径（见 tray.go 包头注释）
